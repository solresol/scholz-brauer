#!/usr/bin/env python3
"""Export candidate alternating-signature certificates; Lean checks all claims.

No proof acceptance occurs in Python. The generated classifier need not be
trusted as a set implementation: the Lean checker explicitly verifies coverage
of every edge and two-edge sum before excluding any singleton.
"""
import argparse
from collections import defaultdict
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import platform
import signal
import subprocess
import time

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / 'results/2026-11-09-placed-pairs.json'
OUT = ROOT / 'lean/ScholzBrauer'


def digit(m, x):
    return (-1 if x // m % 2 else 1) * 4 ** (x % m)


def candidate(m, d):
    digits = [digit(m, x) for x in range(109)]
    edges = sorted({digits[x] + digits[x + d] for x in range(109 - d)})
    sums = sorted({a + b for a in edges for b in edges})
    lookup = set(sums)
    target = sum(digits)
    singletons = [s for s in range(109)
                  if any(target - e - digits[s] in lookup for e in edges)]
    return edges, sums, singletons


def literals(xs):
    return '[' + ', '.join(str(x) if x >= 0 else f'({x})' for x in xs) + ']'


def pairlist(pairs):
    return '[' + ', '.join(f'({m}, {d})' for m, d in pairs) + ']'


def classifier_definitions(label, values):
    """Name small subtrees to avoid copying a giant literal during reduction."""
    lines = []
    count = 0

    def build(xs):
        nonlocal count
        name = f'alternatingLookup_{label}_{count}'
        count += 1
        if len(xs) <= 63:
            body = 'alternating_lookup% ' + json.dumps(json.dumps(xs, separators=(',', ':')))
        else:
            mid = len(xs) // 2
            left, right = build(xs[:mid]), build(xs[mid + 1:])
            pivot = str(xs[mid]) if xs[mid] >= 0 else f'({xs[mid]})'
            body = f'.node {pivot} {left} {right}'
        lines.extend([f'private def {name} : AlternatingLookup :=', f'  {body}', ''])
        return name

    return build(values), lines


def all_chunks(label, values, pred):
    """Keep kernel normalization caches bounded by composing small all checks."""
    lines, names = [], []
    chunks = [values[i:i + 4] for i in range(0, len(values), 4)]
    for i, chunk in enumerate(chunks):
        name = f'{label}_{i}'
        lines += [f'private theorem {name} :',
                  f'    ({literals(chunk)}.all {pred}) = true := by',
                  '  decide +kernel', '']
        names.append(name)
    joined = ' ++ '.join(literals(c) for c in chunks)
    result = ', '.join(names)
    lines += [f'private theorem {label} :',
              f'    ({literals(values)}.all {pred}) = true := by',
              f'  change (({joined}).all {pred}) = true',
              '  simp only [List.all_append, Bool.and_eq_true, and_assoc]',
              f'  exact ⟨{result}⟩', '']
    return lines


def generated():
    source = json.loads(INPUT.read_text())
    empty = sorted(map(tuple, source['directional_rejections']))
    disjoint_all = sorted(map(tuple, source['additional_shared_singleton_rejections']))
    disjoint = [p for p in disjoint_all if p[0] < p[1]]
    if sorted(disjoint + [p[::-1] for p in disjoint]) != disjoint_all:
        raise ValueError('asymmetric shared-singleton rejection input')
    domains = sorted(set(empty + disjoint_all))
    data = {p: candidate(*p) for p in domains}
    for p in empty:
        if data[p][2]:
            raise ValueError(f'candidate does not reject {p}')
    for p in disjoint:
        if set(data[p][2]) & set(data[p[::-1]][2]):
            raise ValueError(f'candidate singleton sets intersect at {p}')
    original = {(e['modulus'], e['opposite_step']): e['singleton_positions']
                for e in source['decisions']}
    for p in domains:
        if not set(original[p]) <= set(data[p][2]):
            raise ValueError(f'candidate loses a saved placement at {p}')
    groups = defaultdict(list)
    for p in domains:
        groups[p[0]].append(p)
    files = {}
    for m, group in sorted(groups.items()):
        text = [
            'import ScholzBrauer.Clift109Alternating', '',
            '/-! Generated by scripts/export_lean_alternating_checks.py.',
            'Candidate data are untrusted; every certificate passes decide +kernel. -/', '',
            'namespace ScholzBrauer.Clift109', '',
            'set_option maxRecDepth 4096',
            'set_option maxHeartbeats 2000000', '',
        ]
        for _, d in group:
            edges, sums, allowed = data[m, d]
            label = f'{m}_{d}'
            classifier, definitions = classifier_definitions(label, sums)
            text += definitions
            text += [
                f'private def alternatingCert_{label} : AlternatingCertificate :=',
                f'  ⟨{literals(edges)},',
                f'    {classifier},',
                f'    {literals(allowed)}, {sum(digit(m, i) for i in range(109))}⟩', '',
            ]
            text += all_chunks(f'alternatingSums_{label}', edges,
                               f'(fun x : ℤ => alternatingCert_{label}.edges.all '
                               f'(fun y => alternatingCert_{label}.pairs.contains (x + y)))')
            text += all_chunks(f'alternatingSingletons_{label}', list(range(109)),
                               f'(fun s : ℕ => alternatingCert_{label}.edges.all (fun z => '
                               f'!alternatingCert_{label}.pairs.contains (alternatingCert_{label}.target - z - '
                               f'alternatingDigit {m} s) || alternatingCert_{label}.singletons.contains s))')
            text += [
                f'private theorem alternatingChecked_{label} :',
                f'    checkAlternating {m} {d} alternatingCert_{label} = true := by',
                '  simp only [checkAlternating, Bool.and_eq_true, and_assoc]',
                f'  refine ⟨?_, ?_, alternatingSums_{label}, alternatingSingletons_{label}⟩',
                '  · decide +kernel', '  · decide +kernel', '',
                f'theorem alternating_allowed_{label} (s : ℤ) (hs : 0 ≤ s ∧ s < 109)',
                f'    (hp : intervalThreePairPlacement {m} {d} s) :',
                f'    s.toNat ∈ ({literals(allowed)} : List ℕ) :=',
                f'  checkAlternating_sound {m} {d} s alternatingCert_{label} (by decide) hs',
                f'    alternatingChecked_{label} hp', '',
            ]
        text += ['end ScholzBrauer.Clift109', '']
        files[OUT / f'Clift109AlternatingChecks{m:02d}.lean'] = '\n'.join(text)

    text = [f'import ScholzBrauer.Clift109AlternatingChecks{m:02d}' for m in groups]
    text += [
        '', '/-! Every finite removal is kernel checked. Survivors need not be feasible. -/', '',
        'namespace ScholzBrauer.Clift109', '',
        'set_option maxRecDepth 4096', 'set_option maxHeartbeats 2000000', '',
        'def alternatingRejectedDirections : List (ℤ × ℤ) :=',
        f'  {pairlist(empty)}', '',
        'def alternatingDisjointPairs : List (ℤ × ℤ) :=',
        f'  {pairlist(disjoint)}', '',
        'theorem alternatingRejectedDirections_checked (p : ℤ × ℤ)',
        '    (hp : p ∈ alternatingRejectedDirections) (s : ℤ) (hs : 0 ≤ s ∧ s < 109) :',
        '    ¬intervalThreePairPlacement p.1 p.2 s := by',
        '  simp only [alternatingRejectedDirections, List.mem_cons, List.not_mem_nil, or_false] at hp',
        '  rcases hp with ' + ' | '.join(['rfl'] * len(empty)),
    ]
    for m, d in empty:
        text += ['  · intro h',
                 f'    simpa only [List.not_mem_nil] using alternating_allowed_{m}_{d} s hs h']
    text += [
        '', 'theorem alternatingDisjointPairs_checked (p : ℤ × ℤ)',
        '    (hp : p ∈ alternatingDisjointPairs) (s : ℤ) (hs : 0 ≤ s ∧ s < 109) :',
        '    ¬(intervalThreePairPlacement p.1 p.2 s ∧ intervalThreePairPlacement p.2 p.1 s) := by',
        '  simp only [alternatingDisjointPairs, List.mem_cons, List.not_mem_nil, or_false] at hp',
        '  rcases hp with ' + ' | '.join(['rfl'] * len(disjoint)),
    ]
    for m, d in disjoint:
        a, b = data[m, d][2], data[d, m][2]
        text += [
            '  · intro h',
            f'    have ha := alternating_allowed_{m}_{d} s hs h.1',
            f'    have hb := alternating_allowed_{d}_{m} s hs h.2',
            f'    have hd : ∀ i ∈ ({literals(a)} : List ℕ), i ∉ ({literals(b)} : List ℕ) := by',
            '      decide +kernel', '    exact hd s.toNat ha hb',
        ]
    text += ['', 'end ScholzBrauer.Clift109', '']
    files[OUT / 'Clift109AlternatingChecks.lean'] = '\n'.join(text)
    return files, data


def main():
    started = time.monotonic()
    signal.alarm(60)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--report', type=Path,
                        help='save a new bounded computational cross-check report')
    args = parser.parse_args()
    if args.report and args.report.exists():
        raise FileExistsError(args.report)
    files, data = generated()
    for path, text in files.items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise ValueError(f'generated source differs: {path}')
        else:
            path.write_text(text)
    summary = {
        'input': str(INPUT.relative_to(ROOT)),
        'input_sha256': hashlib.sha256(INPUT.read_bytes()).hexdigest(),
        'mode': 'compare exact bytes' if args.check else 'export candidate data and proof goals',
        'domains': len(data),
        'classifier_nodes': sum(len(v[1]) for v in data.values()),
        'generated_files': len(files),
        'source_bytes': sum(len(t.encode()) for t in files.values()),
        'lean_proof': False,
        'timeout_seconds': 60,
        'claim_boundary': 'Compilation and axiom audit are separate requirements.',
    }
    if args.report:
        source = json.loads(INPUT.read_text())
        complete = {(e['modulus'], e['opposite_step']): candidate(e['modulus'], e['opposite_step'])[2]
                    for e in source['decisions']}
        for e in source['decisions']:
            if not set(e['singleton_positions']) <= set(complete[e['modulus'], e['opposite_step']]):
                raise ValueError('lost a previously verified placement')
        surviving = sorted(p for p in complete if set(complete[p]) & set(complete[p[::-1]]))
        if surviving != sorted(map(tuple, source['surviving_pairs'])):
            raise ValueError('alternating reduction disagrees with saved exact placement count')
        summary.update(
            accessed_at_utc=datetime.now(timezone.utc).isoformat(),
            base_commit=subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
            python=platform.python_version(), dependencies='Python standard library', random_seed=None,
            bounds={'input_pairs': 344, 'interval': [0, 108], 'radix': 4,
                    'pair_starts': '0 <= x < 109-d; repeated starts allowed in relaxation',
                    'singleton_positions': 109},
            necessary_pair_count=len(surviving), surviving_pairs=surviving,
            decisions=[{'m': m, 'd': d, 'singletons': complete[m, d]}
                       for m, d in sorted(complete)],
            kernel_certificate_domains=[{'m': m, 'd': d, 'edges': len(e), 'two_edge_sums': len(p),
                                        'singletons': s} for (m, d), (e, p, s) in sorted(data.items())],
            elapsed_seconds=time.monotonic() - started,
            input_hashes={str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
                          for p in [INPUT, Path(__file__), OUT / 'Clift109Alternating.lean']},
            generated_sha256={str(p.relative_to(ROOT)): hashlib.sha256(t.encode()).hexdigest()
                              for p, t in files.items()},
        )
        args.report.write_text(json.dumps(summary, indent=2) + '\n')
    print(json.dumps({k: v for k, v in summary.items()
                      if k not in ('decisions', 'surviving_pairs', 'generated_sha256', 'kernel_certificate_domains')},
                     indent=2))


if __name__ == '__main__':
    main()
