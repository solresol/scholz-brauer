#!/usr/bin/env python3
"""Independent enumeration of interval configurations of Clift's 109 graph.

This deliberately differs from `clift109_box_search.cpp` after the box step.
The C++ program halves by d1 (sink side). Here we halve by u (source side):

    C = [0,108] minus (t + SS(u,v,w,d1,d2,d3)) = P(u)+Y  disjoint  A3+R5,
    R5 = R(d1,d2) | {p} | (q+P(d1)),   Y = A1+P(v)+R5  disjoint  A2+R7.

Enumerate the rectangle, pair and point of A3+R5 inside C, halve the rest by
u with a peeling algorithm, then find A2+R7 inside Y and halve the rest by v.
Run parity prunes the point: after removing the rectangle at most three odd
u-runs remain, after the pair exactly one, and the point lies at an even index
in that run. Sets with distinct subset sums are generated by a popcount test
rather than the C++ collision test. Standard library only; exact integers.
"""
import argparse
from itertools import combinations
import json
import time

N = 109
FULL = (1 << N) - 1


def popcount(x):
    return bin(x).count('1')


def bits(m):
    out = []
    while m:
        low = m & -m
        out.append(low.bit_length() - 1)
        m ^= low
    return out


def odd_mask(C, d):
    """Last element of every odd-length run of C in steps of d."""
    X, odd = C, 0
    while X:
        starts = X & ~(X << d)
        single = starts & ~(X >> d)
        odd |= single
        pairs = starts & ~single
        X &= ~(single | pairs | (pairs << d))
    return odd


def halve(C, d):
    """The unique A with A disjoint from A<<d and A|(A<<d)=C, by peeling."""
    A, X = 0, C
    while X:
        starts = X & ~(X << d)
        successors = starts << d
        if successors & ~X:
            return None
        A |= starts
        X &= ~(starts | successors)
    return A


def distinct_subset_sum_sets():
    out = []

    def rec(chosen, sums, total, start):
        if len(chosen) == 6:
            out.append(tuple(chosen))
            return
        for x in range(start, N):
            if total + x > N - 1:
                break
            new = sums | (sums << x)
            if popcount(new) == 2 * popcount(sums):
                rec(chosen + [x], new, total + x, x + 1)

    rec([], 1, 0, 1)
    return out


def partition_ok(u, v, w, d1, d2, d3, t, p, q, A1, A2, A3):
    vals = [t + sum(c) for r in range(7) for c in combinations((u, v, w, d1, d2, d3), r)]
    R7 = [0, d1, d2, d1 + d2, p]
    R5 = R7 + [q, q + d1]
    vals += [A1 + x + y for x in (0, u, v, u + v) for y in R5]
    vals += [A2 + x + y for x in (0, u) for y in R7]
    vals += [A3 + y for y in R5]
    return sorted(vals) == list(range(N))


def search(progress=None):
    found = set()
    sets = distinct_subset_sum_sets()
    stats = {'distinct_subset_sum_sets': len(sets), 'set_offsets': 0, 'w_candidates': 0}
    for index, xs in enumerate(sets):
        box = 1
        for x in xs:
            box |= box << x
        for t in range(N - sum(xs)):
            stats['set_offsets'] += 1
            C = FULL & ~(box << t)
            odd = {x: popcount(odd_mask(C, x)) for x in xs}
            for u in xs:
                if odd[u] > 7:
                    continue
                for d1 in xs:
                    if d1 == u or odd[d1] > 7:
                        continue
                    for d2 in xs:
                        if d2 in (u, d1):
                            continue
                        rest = [x for x in xs if x not in (u, d1, d2)]
                        for a in bits(C):
                            corners = (a, a + d1, a + d2, a + d1 + d2)
                            if any(y >= N or not (C >> y) & 1 for y in corners):
                                continue
                            C1 = C
                            for y in corners:
                                C1 &= ~(1 << y)
                            if popcount(odd_mask(C1, u)) > 3:
                                continue
                            for c in bits(C1):
                                if c + d1 >= N or not (C1 >> (c + d1)) & 1:
                                    continue
                                C2 = C1 & ~((1 << c) | (1 << (c + d1)))
                                om = odd_mask(C2, u)
                                if popcount(om) != 1:
                                    continue
                                b = om.bit_length() - 1
                                while True:
                                    Y = halve(C2 & ~(1 << b), u)
                                    if Y is not None:
                                        stats['w_candidates'] += 1
                                        found |= split_y(Y, u, d1, d2, rest, t, a, b, c)
                                    if b - 2 * u < 0 or not (C2 >> (b - u)) & 1 \
                                            or not (C2 >> (b - 2 * u)) & 1:
                                        break
                                    b -= 2 * u
        if progress and index % 2000 == 0:
            progress(index, len(sets), len(found), stats)
    stats['configurations'] = len(found)
    return sorted(found), stats


def split_y(Y, u, d1, d2, rest, t, a, b, c):
    out = set()
    A3, p, q = a, b - a, c - a
    R7 = [0, d1, d2, d1 + d2, p]
    R5 = R7 + [q, q + d1]
    for v in rest:
        w, d3 = sorted(x for x in rest if x != v)
        for y0 in bits(Y):
            A2 = y0 - min(R7)
            m7 = 0
            for r in R7:
                z = A2 + r
                if z < 0 or z >= N or not (Y >> z) & 1:
                    break
                m7 |= 1 << z
            else:
                H = halve(Y & ~m7, v)
                if H is None:
                    continue
                A1 = (H & -H).bit_length() - 1 - min(R5)
                cfg = (u, v, w, d1, d2, d3, t, p, q, A1, A2, A3)
                if partition_ok(*cfg):
                    out.add(cfg)
    return out


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', required=True)
    args = parser.parse_args()
    with open(args.output, 'x') as handle:
        start = time.perf_counter()
        found, stats = search(lambda i, n, f, s: print(i, n, f, json.dumps(s), flush=True))
        for cfg in found:
            handle.write(' '.join(map(str, cfg)) + '\n')
    stats['seconds'] = round(time.perf_counter() - start, 6)
    print(json.dumps(stats))


if __name__ == '__main__':
    main()
