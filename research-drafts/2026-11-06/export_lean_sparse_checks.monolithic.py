#!/usr/bin/env python3
"""Emit kernel checks for the saved sparse refinement, without an interval search.

The saved two-algorithm report chooses one failing direction for each unordered
rejected pair. Each emitted exclusion is independently reduced by Lean's kernel;
the Python decisions and this emitter are not trusted premises of the theorem.
"""
import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import platform
import signal
import time

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / 'results/2026-11-05-sparse-residue-pairs.json'
OUTPUT = ROOT / 'lean/ScholzBrauer/Clift109SparseChecks.lean'
INPUT_SHA256 = '4c9ce9bafd676be265d58ee3c22d3489ee30197670246f2cafd77e383f30504a'


def edge(m, d, x):
    return (1 << x) ^ (1 << ((x + d) % m))


def edge_lookup(m, d, n):
    q = n.bit_length() - 1 if n else 0
    return n == edge(m, d, q) or n == edge(m, d, (q - d) % m)


def pair_lookup(m, d, n):
    if not n:
        return True
    q = n.bit_length() - 1
    return (edge_lookup(m, d, n ^ edge(m, d, q)) or
            edge_lookup(m, d, n ^ edge(m, d, (q - d) % m)))


def excluded(m, d):
    fingerprint = 0
    for n in range(109):
        fingerprint ^= 1 << (n % m)
    return all(not pair_lookup(m, d, fingerprint ^ edge(m, d, z) ^ (1 << s))
               for z in range(m) for s in range(m))


def render(directions):
    lines = [
        'import ScholzBrauer.Clift109SparseCheck', '',
        '/-! Generated by scripts/export_lean_sparse_checks.py from the saved',
        '606-pair report. Every rejection below is reduced by the kernel;',
        'no Python result is an assumed premise. -/', '',
        'set_option Elab.async false',
        'set_option maxHeartbeats 2000000',
        'set_option maxRecDepth 4096', '',
        'namespace ScholzBrauer.Clift109', '',
    ]
    names = []
    for i, (m, d) in enumerate(directions):
        name = f'sparseRejected_{i:03d}'
        names.append(name)
        lines += [f'private theorem {name} : sparseExcluded {m} {d} = true := by',
                  '  decide +kernel', '']
    lines += [
        '/-- One checked failing direction for each removed unordered pair. -/',
        'def sparseRejectedDirections : List (ℤ × ℤ) :=',
        '  [' + ', '.join(f'({m}, {d})' for m, d in directions) + ']', '',
        'theorem sparseRejectedDirections_checked :',
        '    sparseRejectedDirections.all (fun p => sparseExcluded p.1 p.2) = true := by',
        '  simp only [sparseRejectedDirections, List.all_cons, List.all_nil,',
    ]
    for i in range(0, len(names), 6):
        lines.append('    ' + ', '.join(names[i:i+6]) + ',')
    lines += ['    Bool.true_and]', '', 'end ScholzBrauer.Clift109', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check the generated source without writing')
    parser.add_argument('--report', type=Path)
    args = parser.parse_args()
    signal.alarm(60)
    started = time.monotonic()
    if hashlib.sha256(INPUT.read_bytes()).hexdigest() != INPUT_SHA256:
        raise ValueError('saved report hash changed')
    report = json.loads(INPUT.read_text())
    failures = set()
    for decision in report['decisions']:
        m, d = decision['modulus'], decision['step']
        if excluded(m, d) != (not decision['compatible']):
            raise ValueError(f'top-bit lookup disagrees with saved algorithms at {(m, d)}')
        if not decision['compatible']:
            failures.add((m, d))
    directions = sorted({min(q for q in (tuple(p), tuple(p[::-1])) if q in failures)
                         for p in report['removed_pairs']})
    if len(directions) != 131:
        raise ValueError('unexpected rejection cover')
    text = render(directions)
    if args.check:
        if OUTPUT.read_text() != text:
            raise ValueError('generated Lean source differs')
    else:
        with OUTPUT.open('x') as stream:
            stream.write(text)
    evidence = {
        'recorded_at_utc': datetime.now(timezone.utc).isoformat(),
        'python': platform.python_version(),
        'dependencies': 'Python standard library only', 'random_seed': None,
        'timeout_seconds': 60, 'elapsed_seconds': time.monotonic() - started,
        'input_sha256': INPUT_SHA256,
        'output_sha256': hashlib.sha256(text.encode()).hexdigest(),
        'directional_decisions_compared': len(report['decisions']),
        'checked_directions_emitted': len(directions),
        'ordered_pairs_covered': len(report['removed_pairs']),
        'bounds': {'interval': [0, 108], 'each_residue': '0 <= residue < modulus',
                   'largest_modulus': max(m for m, _ in directions),
                   'targets_in_emitted_checks': sum(m*m for m, _ in directions)},
        'claim_boundary': 'Reproducible proof-source generation and exact computational '
                          'cross-check, not itself kernel validation, interval feasibility, '
                          'cap classification or the full selected-109 exclusion.',
    }
    if args.report:
        with args.report.open('x') as stream:
            json.dump(evidence, stream, indent=2)
            stream.write('\n')
    print(json.dumps(evidence, indent=2))


if __name__ == '__main__':
    main()
